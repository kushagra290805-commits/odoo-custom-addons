    def _synthesize_structure(self, context: RenderingContext):
        """
        Phase 47.9 (U8): build the complete base React project structure without
        running the final validation gate. Renderer subclasses extend the
        structure first and validate the final composition exactly once.
        Returns (project_structure, library_files).
        """
        render_project: RenderProject = context.render_project
        manifest: ComponentManifest = context.manifest
        if manifest is None:
            manifest = ComponentManifest.from_render_project(render_project)
            context.manifest = manifest

        project_structure: Dict[str, str] = {}

        # 1. Generate Project Configs
        project_structure['package.json'] = self._generate_package_json(render_project, context)
        project_structure['vite.config.js'] = self._generate_vite_config(context)
        # Phase 47.23 (ADR-0075): the shipped document loads the theme's
        # webfonts (derived from the font tokens the pipeline injects).
        project_structure['index.html'] = self._generate_root_html(
            render_project, font_families=self._theme_font_families(context))
        project_structure['src/main.jsx'] = self._generate_main_jsx()
        # Phase 47.24 (ADR-0076): cn() utility for external components that
        # import from '@/lib/utils' (shadcn registry code).
        if self._needs_tailwind(context):
            project_structure['src/lib/utils.js'] = self._generate_utils_js()
        # Phase 47.36: the ONE canonical Client API client module — emitted
        # ONLY when the Project Capability Contract enables a Client API
        # binding (backend-required projects). Static/presentational
        # projects receive no API client and no proxy.
        if self._client_api_binding(context)['enabled']:
            project_structure['src/lib/clientApi.js'] = self._generate_client_api_js()
            # Phase 47.41: the ONE app-level cart state owner ships with
            # the commerce-capable scaffold (clientApi.js precedent).
            if self._client_api_binding(context)['products']:
                project_structure['src/lib/cart.js'] = self._generate_cart_js()

        # 2. Generate Design Tokens
        project_structure.update(self.generate_design_tokens(context))

        # 3. Generate Asset Binding Layer
        project_structure.update(self.generate_assets(context))

        # 4. Generate Content Binding Layer
        project_structure['src/config/content.js'] = self._generate_content_js(
            getattr(render_project, "global_content", []),
            getattr(render_project, "pages", [])
        )

        # 4.5 Generate Provider-Neutral Component Manifest & Reusable Library
        project_structure['src/config/manifest.js'] = self._generate_manifest_js(manifest)
        library = ReactComponentLibrary(manifest, interaction_model=context.interaction_model)
        library_files = library.synthesize_all()

        # 5. Generate Reusable Layout Components
        project_structure.update(self.generate_layouts(context))

        # 6. Generate Reusable Section Components (including library components and unified barrel index.js)
        project_structure.update(self.generate_components(context))

        # 7. Generate Page Components
        project_structure.update(self.generate_pages(context))

        # 8. Generate Routing (src/routes.jsx & src/App.jsx)
        project_structure.update(self.generate_routes(context))

        return project_structure, library_files

    def _build_result(self, context: RenderingContext, project_structure: Dict[str, str],
                      library_files: List[str], val_res: Dict[str, Any],
                      extra_metadata: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Shared provider result contract builder (Phase 47.9 U8)."""
        render_project: RenderProject = context.render_project
        provider_id = self.get_metadata().provider_id

        try:
            dependencies = json.loads(project_structure.get('package.json', '{}')).get('dependencies', {})
        except (json.JSONDecodeError, AttributeError, TypeError):
            dependencies = {}

        if not val_res.get("valid", False):
            return {
                "status": "error",
                "provider": provider_id,
                "project_name": render_project.name,
                "project_structure": project_structure,
                "dependencies": dependencies,
                "validation": val_res,
                "errors": val_res.get("errors", []),
            }

        pages_generated = [p for p in project_structure if p.startswith("src/pages/")]
        layouts_generated = [l for l in project_structure if l.startswith("src/layouts/")]
        sec_components_generated = [c for c in project_structure if c.startswith("src/components/") and c != "src/components/index.js" and c not in library_files]

        metadata = {
            "pages_generated": len(pages_generated),
            "components_generated": len(sec_components_generated),
            "library_components_synthesized": len(library_files) - 1,
            "layouts_generated": len(layouts_generated),
            "tokens_mapped": len(getattr(render_project, "tokens", [])),
            "assets_bound": len(getattr(render_project, "global_assets", [])),
            "content_bundles_bound": len(getattr(render_project, "global_content", [])),
            "archetypes_supported": getattr(render_project, "metadata", {}).get('archetypes_present', []),
            "planning_layer_frozen": "ADR-0035",
            "renderer_version": "1.0.0",
            "provider_version": "1.0.0",
            "renderer_strategy": (context.output_config or {}).get("rendering_strategy", "none"),
            "capabilities": self.get_metadata().capabilities.to_dict(),
        }
        if extra_metadata:
            metadata.update(extra_metadata)

        return {
            "status": "success",
            "provider": provider_id,
            "project_name": render_project.name,
            "version": getattr(render_project, "version", "1.0.0"),
            "project_structure": project_structure,
            "dependencies": dependencies,
            "validation": val_res,
            "metadata": metadata,
            "supported_operations_executed": ["build_render_project", "generate_react_project", "validate_design"],
            "unsupported_granular_operations_deferred": [
                "create_page (requires interactive canvas mutation)",
                "create_component (requires interactive canvas mutation)",
                "export_svg (requires rendering engine canvas execution)",
                "export_png (requires rendering engine canvas execution)",
                "export_pdf (requires rendering engine canvas execution)"
            ],
            "note": "React Generation Engine executed successfully on frozen AI planning layer (ADR-0035)."
        }

    def generate_project(self, context: RenderingContext) -> Dict[str, Any]:
        """
        Stage 2: Synthesize a complete, production-ready React application from RenderingContext.
        """
        project_structure, library_files = self._synthesize_structure(context)

        # Execute structural validation contract
        self.validate_manifest(context)
        val_res = self.validate_project(context, project_structure)
        if not val_res.get("valid", False):
            _logger.warning("Project validation generated warnings/errors: %s", val_res.get("errors"))

        _logger.info("ReactRenderingProvider complete: Synthesized %d React project files for '%s'.",
                     len(project_structure), context.render_project.name)

        # Phase 47.9 (U8): invalid provider output is a generation failure, not a
        # silent warning. The pipeline bridge (DesignOrchestrationEngine) maps
        # status != success to EngineExecutionResult(success=False).
        return self._build_result(context, project_structure, library_files, val_res)

